print("========== Standard Library Tour ==========")

# Import standard library modules
import math
import random
import datetime
import statistics

# Math module
number = 25
print("Square root:", math.sqrt(number))
print("Ceiling:", math.ceil(4.3))

# Random module
numbers = [10, 20, 30, 40, 50]
print("Random number:", random.choice(numbers))

# DateTime module
today = datetime.date.today()
print("Today's date:", today)

# Statistics module
marks = [80, 90, 75, 85, 95]
print("Average marks:", statistics.mean(marks))
print("Highest marks:", max(marks))
print("Lowest marks:", min(marks))

